import { readFileSync, appendFileSync } from 'node:fs';
import { client } from './github.mjs';
import { evaluate } from './guard.mjs';

const MARKER = '<!-- release-bot -->';
const LABEL = 'needs-human';

const repo = process.env.GITHUB_REPOSITORY;
const config = JSON.parse(readFileSync(process.env.SDK_CONFIG, 'utf8'));
const gh = client(process.env.GITHUB_TOKEN);

const run = await gh.get(`/repos/${repo}/actions/runs/${process.env.RUN_ID}`);
const owner = repo.split('/')[0];
const [listed] = await gh.get(`/repos/${repo}/pulls?state=open&head=${owner}:${encodeURIComponent(run.head_branch)}`);
if (!listed) {
  console.log(`No open PR for ${run.head_branch}; nothing to do.`);
  process.exit(0);
}

const pr = await gh.get(`/repos/${repo}/pulls/${listed.number}`);
if (pr.user.login !== config.prAuthor && !pr.head.ref.startsWith(config.branchPrefix)) {
  console.log(`#${pr.number} is not a Speakeasy PR; leaving it to humans.`);
  process.exit(0);
}

const [commits, files, genignore] = await Promise.all([
  gh.paginate(`/repos/${repo}/pulls/${pr.number}/commits`),
  gh.paginate(`/repos/${repo}/pulls/${pr.number}/files`),
  readGenignore(pr.base.sha),
]);
const { ok, reasons } = evaluate({ pr, run, commits, files, config, genignore });

if (ok) {
  console.log(`#${pr.number} passes every rule; approving and merging ${pr.head.sha}.`);
  await gh.post(`/repos/${repo}/pulls/${pr.number}/reviews`, {
    commit_id: pr.head.sha,
    event: 'APPROVE',
    body: 'Generated by Speakeasy and within the path guards.',
  });
  await gh.put(`/repos/${repo}/pulls/${pr.number}/merge`, {
    sha: pr.head.sha,
    merge_method: 'squash',
    commit_title: `${pr.title} (#${pr.number})`,
  });
  await gh.delete(`/repos/${repo}/git/refs/heads/${encodeURIComponent(pr.head.ref)}`).catch(() => {});
  output({ verdict: 'merged', pr: pr.number });
} else {
  console.log(`#${pr.number} needs a human:\n- ${reasons.join('\n- ')}`);
  const alreadyFlagged = pr.labels.some((l) => l.name === LABEL);
  await gh.post(`/repos/${repo}/issues/${pr.number}/labels`, { labels: [LABEL] });
  await upsertComment(pr.number, reasons);
  output({ verdict: 'human', pr: pr.number, notify: String(!alreadyFlagged) });
}

async function readGenignore(ref) {
  try {
    const file = await gh.get(`/repos/${repo}/contents/.genignore?ref=${ref}`);
    return Buffer.from(file.content, 'base64').toString('utf8')
      .split('\n').map((l) => l.trim()).filter((l) => l && !l.startsWith('#'));
  } catch (err) {
    if (err.status === 404) return [];
    throw err;
  }
}

async function upsertComment(number, reasons) {
  const body = `${MARKER}\nThe release bot will not merge this PR. A developer needs to review it:\n\n${reasons.map((r) => `- ${r}`).join('\n')}`;
  const comments = await gh.paginate(`/repos/${repo}/issues/${number}/comments`);
  const mine = comments.find((c) => c.body.startsWith(MARKER) && c.user.type === 'Bot');
  if (mine) await gh.patch(`/repos/${repo}/issues/comments/${mine.id}`, { body });
  else await gh.post(`/repos/${repo}/issues/${number}/comments`, { body });
}

function output(values) {
  if (!process.env.GITHUB_OUTPUT) return;
  appendFileSync(process.env.GITHUB_OUTPUT, Object.entries(values).map(([k, v]) => `${k}=${v}\n`).join(''));
}
